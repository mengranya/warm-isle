function fixedScenario(book, { name, start, end, description, template, title }) {
  const safeStart = Math.max(Number(start), book.era.startYear);
  const safeEnd = Math.min(Number(end), book.era.endYear);
  if (safeStart > safeEnd) return null;
  start = safeStart;
  end = safeEnd;
  return {
    id: `sb_special_${book.id}_fixed_${name}`,
    title: `${name} · ${title}`,
    description: `${name}，${description}。${book.name}固定历史人物。`,
    location: book.defaults?.location || book.name,
    opening:
      `你是${name}。${description}。此刻，${book.name}的局势正把你推向一个必须作出决定的节点：` +
      `身边有人等待你的命令，也有人等着看你犯错。你的身份已经写进史书，能改变的只有接下来的选择。`,
    choices: ['召见心腹，先听各方意见', '按自己的判断直接行动', '暂缓一步，观察局势'],
    inventory: [],
    money: book.defaults?.startingMoney || 10,
    realm: title,
    titleLabel: name,
    template,
    fixedFigure: {
      name,
      title,
      description,
      template,
      age: '35',
      gender: '未设定',
      yearStart: start,
      yearEnd: end,
    },
    yearStart: start,
    yearEnd: end,
    creationMode: 'fixed',
  };
}

export function attachSpecialOpenings(book) {
  if (!book?.era || book.era.enabled === false) return book;
  const existing = new Set((book.scenarios || []).map((scenario) => scenario.id));
  const add = (scenario) => {
    if (!scenario || existing.has(scenario.id)) return;
    existing.add(scenario.id);
    book.scenarios.push(scenario);
  };
  for (const role of ['civil', 'military', 'merchant', 'commoner']) {
    add(roleScenario(book, role));
  }
  for (const [name, start, end, description] of RULERS[book.id] || []) {
    add(
      fixedScenario(book, {
        name,
        start,
        end,
        description,
        template: 'emperor',
        title: '君主',
      }),
    );
  }
  for (const [name, start, end] of EXTRA_EMPERORS[book.id] || []) {
    add(
      fixedScenario(book, {
        name,
        start,
        end,
        description: `${book.name}君主，按在位年份收录的皇帝身份卡`,
        template: 'emperor',
        title: '皇帝',
      }),
    );
  }
  for (const [name, start, end, description, template, title] of FAMOUS[book.id] || []) {
    add(
      fixedScenario(book, {
        name,
        start,
        end,
        description,
        template,
        title: title || (template === 'military' ? '名将' : '名士'),
      }),
    );
  }
  for (const [name, start, end, description, template, title] of EXTRA_FAMOUS[book.id] || []) {
    add(
      fixedScenario(book, {
        name,
        start,
        end,
        description,
        template,
        title: title || (template === 'military' ? '名将' : '名士'),
      }),
    );
  }
  if (book.id === 'sb_world_republic') {
    for (const [name, start, end, description, template] of REPUBLIC_FIGURES) {
      add(
        fixedScenario(book, {
          name,
          start,
          end,
          description,
          template,
          title:
            template === 'military'
              ? '军政领袖'
              : template === 'merchant'
                ? '实业家'
                : '政治领袖',
        }),
      );
    }
  }
  return book;
}
